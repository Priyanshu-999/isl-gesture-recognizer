"""Train the gesture classifier and report honest, measured accuracy.

Model choice, in plain language: the sequence is flattened to 1,890
numbers (see common.py), standardised, and classified with a
RandomForest. No GPU is needed and training takes seconds on a normal
laptop. A recurrent LSTM would model time more directly, but it needs
TensorFlow, longer training and more data than a first demo has; the
flattened forest is the honest "simple classifier over landmark
sequences" from the design, and the file is structured so an LSTM can
replace `build_model()` later without touching data loading or the demo.

Data priority:
  1. Real recordings in data/<gesture>/*.npy (from collect_data.py).
  2. If none exist, the clearly-labelled synthetic sample data in
     data/sample/sample_landmarks.npz (generated by
     generate_sample_data.py). The report then says dataset_type =
     "synthetic" in big letters -- never present that number as
     real-gesture accuracy.

Evaluation: a stratified 80/20 split, so every gesture appears in both
train and test in the same proportion, with a fixed random seed so the
result is reproducible. The headline number is accuracy on the HELD-OUT
20% the model never trained on, plus a confusion matrix and per-class
precision/recall, saved under results/.

Usage:
    python generate_sample_data.py        # only if no real data yet
    python train.py                        # trains, evaluates, saves model
    python train.py --data-dir data        # explicit real-data folder
"""

from __future__ import annotations

import argparse
import json
import pathlib

import numpy as np

from common import FEATURES_PER_SAMPLE, GESTURES, sequence_to_features

MODEL_PATH = pathlib.Path("models") / "gesture_model.joblib"
RESULTS_DIR = pathlib.Path("results")


def load_real_data(data_dir: pathlib.Path):
    """Load .npy sequences from data/<gesture>/ folders.

    Returns (X, y) with X shaped (n, 30, 21, 3), or (None, None) when
    no usable real samples exist, so the caller can fall back to
    synthetic data instead of crashing.
    """
    sequences, labels = [], []
    for gesture in GESTURES:
        folder = data_dir / gesture
        if not folder.exists():
            continue
        for path in sorted(folder.glob("*.npy")):
            try:
                sample = np.load(path)
            except Exception:
                continue
            if sample.shape == (30, 21, 3):
                sequences.append(sample)
                labels.append(gesture)
    if not sequences:
        return None, None
    return np.stack(sequences), np.array(labels)


def load_sample_data(path: pathlib.Path):
    """Load the synthetic sample dataset (see generate_sample_data.py)."""
    bundle = np.load(path, allow_pickle=False)
    return bundle["X"], bundle["y"]


def build_model():
    """Build the classifier pipeline: scaler + RandomForest.

    RandomForest is chosen because it trains fast on CPU, handles the
    1,890 correlated landmark features without careful tuning, and is
    less fragile than a small neural net on a few hundred samples.
    300 trees, fixed random_state, is a reasonable default -- tune it
    only after you have real data and the held-out score to compare.
    """
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.pipeline import Pipeline
    from sklearn.preprocessing import StandardScaler

    return Pipeline([
        ("scaler", StandardScaler()),
        ("forest", RandomForestClassifier(
            n_estimators=300, random_state=42, n_jobs=-1)),
    ])


def evaluate(model, X_test, y_test) -> dict:
    """Return accuracy, per-class report and confusion matrix as plain data."""
    from sklearn.metrics import accuracy_score, classification_report, confusion_matrix

    predicted = model.predict(X_test)
    report = classification_report(y_test, predicted, output_dict=True, zero_division=0)
    return {
        "accuracy": float(accuracy_score(y_test, predicted)),
        "per_class": {
            label: {
                "precision": round(float(stats["precision"]), 4),
                "recall": round(float(stats["recall"]), 4),
                "f1": round(float(stats["f1-score"]), 4),
                "support": int(stats["support"]),
            }
            for label, stats in report.items()
            if label in GESTURES
        },
        "confusion_matrix": confusion_matrix(y_test, predicted, labels=GESTURES).tolist(),
        "labels": GESTURES,
        "test_size": int(len(y_test)),
    }


def plot_results(metrics: dict, results_dir: pathlib.Path) -> None:
    """Save confusion-matrix and per-class F1 charts under results/."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    labels = metrics["labels"]
    matrix = np.array(metrics["confusion_matrix"])

    fig, ax = plt.subplots(figsize=(8, 6))
    image = ax.imshow(matrix, cmap="Blues")
    ax.set_xticks(range(len(labels)), labels, rotation=45, ha="right")
    ax.set_yticks(range(len(labels)), labels)
    ax.set_xlabel("Predicted gesture")
    ax.set_ylabel("True gesture")
    ax.set_title("Confusion matrix (held-out test set)")
    for i in range(len(labels)):
        for j in range(len(labels)):
            ax.text(j, i, matrix[i, j], ha="center", va="center")
    fig.colorbar(image, ax=ax)
    fig.tight_layout()
    fig.savefig(results_dir / "confusion_matrix.png", dpi=150)
    plt.close(fig)

    f1_scores = [metrics["per_class"][label]["f1"] for label in labels]
    fig, ax = plt.subplots(figsize=(8, 4))
    ax.bar(labels, f1_scores, color="#2a7fff")
    ax.set_ylim(0, 1.05)
    ax.set_ylabel("F1 score")
    ax.set_title("Per-gesture F1 score (held-out test set)")
    ax.tick_params(axis="x", rotation=30)
    for x, value in enumerate(f1_scores):
        ax.text(x, value + 0.02, f"{value:.2f}", ha="center")
    fig.tight_layout()
    fig.savefig(results_dir / "per_class_f1.png", dpi=150)
    plt.close(fig)


def main() -> None:
    """CLI: train, evaluate on held-out data, save model + results/."""
    import joblib
    from sklearn.model_selection import train_test_split

    parser = argparse.ArgumentParser(description="Train the gesture classifier.")
    parser.add_argument("--data-dir", default="data")
    parser.add_argument("--test-size", type=float, default=0.2)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    data_dir = pathlib.Path(args.data_dir)
    X, y = load_real_data(data_dir)
    dataset_type = "real"
    if X is None:
        sample_path = data_dir / "sample" / "sample_landmarks.npz"
        if not sample_path.exists():
            raise SystemExit(
                "No real data in data/<gesture>/ and no sample data found.\n"
                "Run: python generate_sample_data.py   (synthetic, for testing only)\n"
                "or:  python collect_data.py --gesture hello --samples 20  (real data)"
            )
        X, y = load_sample_data(sample_path)
        dataset_type = "synthetic"
        print("WARNING: training on SYNTHETIC sample data -- results are NOT")
        print("real-gesture accuracy. Record real samples and retrain.")

    print(f"Dataset: {dataset_type}  samples={len(y)}")
    for gesture in GESTURES:
        print(f"  {gesture:12s} {(y == gesture).sum():4d} samples")

    features = np.stack([sequence_to_features(seq) for seq in X])
    assert features.shape[1] == FEATURES_PER_SAMPLE

    X_train, X_test, y_train, y_test = train_test_split(
        features, y, test_size=args.test_size, random_state=args.seed, stratify=y)
    model = build_model()
    model.fit(X_train, y_train)
    metrics = evaluate(model, X_test, y_test)
    metrics["dataset_type"] = dataset_type
    metrics["train_size"] = int(len(y_train))
    metrics["model"] = "StandardScaler + RandomForest (300 trees, seed 42)"
    metrics["note"] = (
        "SYNTHETIC results only -- not real-gesture accuracy."
        if dataset_type == "synthetic"
        else "Real recorded data, held-out test split."
    )

    MODEL_PATH.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump({"model": model, "labels": GESTURES}, MODEL_PATH)
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    (RESULTS_DIR / "metrics.json").write_text(json.dumps(metrics, indent=2))
    plot_results(metrics, RESULTS_DIR)

    print(f"\nHeld-out accuracy ({dataset_type}): {metrics['accuracy']:.4f} "
          f"on {metrics['test_size']} test samples")
    print(f"Model saved to {MODEL_PATH}")
    print(f"Metrics: {RESULTS_DIR / 'metrics.json'}")
    print(f"Charts:  {RESULTS_DIR / 'confusion_matrix.png'}, "
          f"{RESULTS_DIR / 'per_class_f1.png'}")


if __name__ == "__main__":
    main()
